package mcsrc

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.Nested
import org.gradle.api.tasks.UntrackedTask
import org.gradle.jvm.toolchain.JavaLanguageVersion
import org.gradle.jvm.toolchain.JavaLauncher
import org.gradle.jvm.toolchain.JavaToolchainService
import org.gradle.process.ExecOperations
import org.jetbrains.java.decompiler.main.decompiler.ConsoleDecompiler
import java.nio.file.Path
import javax.inject.Inject
import kotlin.io.path.ExperimentalPathApi
import kotlin.io.path.copyTo
import kotlin.io.path.createDirectories
import kotlin.io.path.deleteRecursively
import kotlin.io.path.exists
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.name
import kotlin.io.path.relativeTo
import kotlin.io.path.walk
import kotlin.io.path.writeText

/**
 * Writes per-class patches of the decompiled Minecraft client from one version to others into [outputDir], a local,
 * greppable take on mcsrc.dev for checking logic against other clients. The versions come from Mojang's version
 * manifest, refreshed on every run and read from [cacheDir] when offline; the patches come from the [SourceCache] in
 * [cacheDir], which every worktree shares.
 */
@OptIn(ExperimentalPathApi::class)
@UntrackedTask(because = "Manages its own cache and output; the decompiled trees are too large to snapshot.")
abstract class MinecraftPatchTask : DefaultTask() {
    @get:Input
    abstract val decompilerMaxHeap: Property<String>

    @get:Internal
    abstract val cacheDir: DirectoryProperty

    @get:Internal
    abstract val outputDir: DirectoryProperty

    @get:Nested
    abstract val javaLauncher: Property<JavaLauncher>

    @get:Inject
    abstract val execOperations: ExecOperations

    @get:Inject
    abstract val toolchains: JavaToolchainService

    init {
        group = "minecraft"
        javaLauncher.convention(toolchains.launcherFor { languageVersion.set(JavaLanguageVersion.of(25)) })
    }

    protected fun meta(): MojangMeta = MojangMeta(cacheDir.get().asFile.toPath().resolve("mojang"))

    protected fun sourceCache(meta: MojangMeta): SourceCache {
        val decompiler = Decompiler { jar, output, options ->
            execOperations.javaexec {
                executable = javaLauncher.get().executablePath.asFile.absolutePath
                classpath(SourceCache.VINEFLOWER_JAR.toFile())
                mainClass.set(ConsoleDecompiler::class.java.name)
                maxHeapSize = decompilerMaxHeap.get()
                args(options + listOf(jar.toString(), output.toString()))
            }
        }
        return SourceCache(cacheDir.get().asFile.toPath(), meta, decompiler, logger)
    }

    /**
     * Fills [outputDir] with the patches from [from] to each of [targets], newest first, and a README that opens with
     * [summary]; anything else in it is removed.
     */
    protected fun publish(meta: MojangMeta, from: VersionEntry, targets: List<VersionEntry>, summary: String) {
        val output = outputDir.get().asFile.toPath()
        claimOutput(output)
        val cache = sourceCache(meta)
        val published = targets.map { target ->
            val cached = cache.patches(from, target)
            val copy = output.resolve(cached.name)
            if (SourceCache.stampOf(copy) != SourceCache.stampOf(cached)) {
                copy.deleteRecursively()
                for (file in cached.walk()) {
                    val destination = copy.resolve(file.relativeTo(cached).toString())
                    destination.parent.createDirectories()
                    file.copyTo(destination)
                }
            }
            copy.name
        }
        val keep = published.toSet() + setOf(MARKER, README)
        for (child in output.listDirectoryEntries()) {
            if (child.name !in keep) child.deleteRecursively()
        }
        output.resolve(README).writeText(readme(from, targets, summary))
        logger.lifecycle("mcsrc: ${published.size} patch sets from ${from.id} are in $output")
    }

    /** The output directory is wiped and rewritten, so refuse to take over one this task did not create. */
    private fun claimOutput(output: Path) {
        val marker = output.resolve(MARKER)
        if (output.exists() && !marker.exists() && output.listDirectoryEntries().isNotEmpty()) {
            throw GradleException("$output exists and was not created by ./gradlew $name; move it away or pick another output")
        }
        output.createDirectories()
        marker.writeText("Generated by ./gradlew $name; everything in this directory is overwritten.\n")
    }

    private fun readme(from: VersionEntry, targets: List<VersionEntry>, summary: String) = buildString {
        appendLine("# Minecraft client patches from ${from.id}")
        appendLine()
        appendLine("Generated by `./gradlew $name` (Mojang names, decompiled with Vineflower). Do not edit or commit.")
        appendLine()
        appendLine(summary)
        appendLine()
        appendLine("Patch sets: ${targets.joinToString(", ") { "`${from.id}_to_${it.id}`" }.ifEmpty { "none" }}.")
        appendLine()
        appendLine("Each `${from.id}_to_<version>/` holds one unified diff per class: `-` lines are ${from.id}, `+` lines are")
        appendLine("that version. A patch sits at the path of the ${from.id} class it changes")
        appendLine("(`net/minecraft/world/entity/LivingEntity.java.patch`), and `CHANGES.txt` lists every class that differs.")
        appendLine()
        appendLine("Releases before 26.1 were obfuscated and carry no local variable names. Patches to them name locals and parameters")
        appendLine("from their type (`level`, `blockpos`, `i`) on both sides, so they show logic changes rather than renames; their")
        appendLine("context lines will not match the names in the ${from.id} source. Patches between later versions keep Mojang's names.")
        appendLine()
        appendLine("Some classes were renamed by letter case only (`Enderman` <-> `EnderMan`). Where their patch files would collide")
        appendLine("on a case-insensitive file system, the later one gets a numbered suffix (`Enderman.java.2.patch`, noted in")
        appendLine("`CHANGES.txt`).")
    }

    protected companion object {
        const val MARKER = ".mcsrc"
        const val README = "README.md"
    }
}
